    #[tokio::test]
    async fn console_enforces_script_csp_without_inline_handlers() {
        let app = build_router(AppState {
            db: Arc::new(Mutex::new(Database::open_in_memory().expect("database"))),
            bearer_token: "test".to_owned(),
            orchestrator: None,
            remote: Arc::new(crate::remote::RemoteManager::new()),
        });
        let response = app
            .oneshot(
                Request::builder()
                    .uri("/")
                    .header("Host", "127.0.0.1:41738")
                    .body(Body::empty())
                    .expect("request"),
            )
            .await
            .expect("response");
        let csp = response
            .headers()
            .get("content-security-policy")
            .expect("CSP")
            .to_str()
            .expect("header");
        assert!(csp.contains("script-src 'self'"));
        assert!(
            !csp.split(';')
                .find(|directive| directive.trim().starts_with("script-src"))
                .expect("script policy")
                .contains("'unsafe-inline'")
        );
        let body = axum::body::to_bytes(response.into_body(), usize::MAX)
            .await
            .expect("body");
        let html = std::str::from_utf8(&body).expect("UTF-8");
        let branding = gnomcode_core::branding::branding().expect("branding");
        assert!(html.contains(&format!("data-base-url=\"{}\"", branding.base_url)));
        assert!(!html.contains("__GNOMCODE_BASE_URL__"));
        assert!(!html.contains("<script>"));
        assert!(!html.contains(" onclick="));
        assert!(!html.contains(" onchange="));
        assert!(!html.contains(" onsubmit="));
    }


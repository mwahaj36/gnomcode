//! Local loopback axum HTTP & WebSocket API (`SPEC §3.1`, `§4.4`).
//!
//! Enforces:
//! 1. Strict loopback binding (`127.0.0.1`).
//! 2. `Host` and `Origin` header validation against `127.0.0.1` and `localhost` (DNS rebinding defense).
//! 3. Bearer token authorization on all endpoints.

use axum::{
    Router,
    extract::{Path, Query, State},
    http::{HeaderMap, StatusCode, header},
    response::{IntoResponse, Json, Redirect},
    routing::{get, post},
};
use fleethud_core::rules::GuardrailRule;
use fleethud_store::{Database, UserProfile};
use serde::{Deserialize, Serialize};
use serde_json::{Value, json};
use std::sync::Arc;
use tokio::sync::Mutex;

/// Server application state shared across HTTP handlers.
#[derive(Clone)]
pub struct AppState {
    /// Database handle wrapped with tokio Mutex.
    pub db: Arc<Mutex<Database>>,
    /// Expected bearer token generated by `DaemonLock`.
    pub bearer_token: String,
}

/// Query parameters for listing sessions with pagination & filters.
#[derive(Debug, Deserialize, Default)]
pub struct SessionQueryParams {
    /// 1-indexed page number.
    pub page: Option<usize>,
    /// Limit per page (default 10).
    pub limit: Option<usize>,
    /// Agent slug filter (e.g. `antigravity`, `codex`, `claude-code`, or `all`).
    pub agent: Option<String>,
    /// Status filter (`active`, `idle`, or `all`).
    pub status: Option<String>,
}

/// Query parameters for reports.
#[derive(Debug, Deserialize, Default)]
pub struct ReportQueryParams {
    /// Range filter (`today`, `7d`, `30d`, `all`, `custom`).
    pub range: Option<String>,
    /// Custom ISO start timestamp.
    pub from: Option<String>,
    /// Custom ISO end timestamp.
    pub to: Option<String>,
    /// Output format (`json` or `csv`).
    pub format: Option<String>,
}

/// Daemon health endpoint response.
#[derive(Debug, Serialize)]
pub struct HealthResponse {
    /// Server health status.
    pub status: &'static str,
    /// Current UTC timestamp.
    pub timestamp: String,
}


/// Server application state shared across HTTP handlers.
#[derive(Clone)]
pub struct AppState {
    /// Database handle wrapped with tokio Mutex.
    pub db: Arc<Mutex<Database>>,
    /// Expected bearer token generated by `DaemonLock`.
    pub bearer_token: String,
    /// Handle used to trigger an immediate local reconciliation.
    pub orchestrator: Option<Arc<crate::DaemonOrchestrator>>,
    /// Opt-in encrypted remote connection state.
    pub remote: Arc<crate::remote::RemoteManager>,
}

/// Daemon health endpoint response.
#[derive(Debug, Serialize)]
pub struct HealthResponse {
    /// Server health status.
    pub status: &'static str,
    /// Version of the running Rust engine.
    pub version: &'static str,
    /// Current UTC timestamp.
    pub timestamp: String,
}


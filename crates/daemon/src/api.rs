    Router::new()
        .route("/", get(console_handler))
        .route("/console", get(console_handler))
        .route("/favicon.ico", get(favicon_handler))
        .route("/fleethud.svg", get(svg_icon_handler))
        .route("/auth/callback", get(auth_callback_handler))
        .route("/health", get(health_handler))
        .route("/api/v1/sessions", get(list_sessions_handler))
        .route("/api/v1/sessions/{id}/focus", post(focus_session_handler))
        .route("/api/v1/report", get(report_handler))
        .route("/api/v1/quota", get(quota_handler))
        .route(
            "/api/v1/user",
            get(user_get_handler).post(user_post_handler),
        )
        .route(
            "/api/v1/pricing/custom",
            get(custom_pricing_get_handler)
                .post(custom_pricing_post_handler)
                .delete(custom_pricing_delete_handler),
        )
        .route("/api/v1/pricing/models", get(pricing_models_handler))
        .route("/api/v1/pricing/refresh", post(pricing_refresh_handler))
        .route(
            "/api/v1/auth/session",
            get(auth_session_get_handler)
                .post(auth_session_post_handler)
                .delete(auth_session_delete_handler),
        )
        .route("/api/v1/stats", get(stats_handler))
        .route("/api/v1/supabase-config", get(supabase_config_handler))
        .route("/api/v1/live", get(live_snapshot_handler))
        .route(
            "/api/v1/rules",
            get(rules_get_handler).post(rules_post_handler),
        )
        .route(
            "/api/v1/rules/{id}",
            axum::routing::delete(rule_delete_handler),
        )
        .route("/api/v1/alerts", get(alerts_get_handler))
        .route("/api/v1/export", get(export_handler))
        .route(
            "/api/v1/license",
            get(license_get_handler)
                .post(license_post_handler)
                .delete(license_delete_handler),
        )
        .route("/api/v1/resume-queue", get(resume_queue_get_handler))
        .route("/api/v1/resume-queue/arm", post(resume_queue_arm_handler))

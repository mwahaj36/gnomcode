#[derive(Serialize)]
pub(crate) struct QuotaPoolView {
    #[serde(flatten)]
    snapshot: gnomcode_core::QuotaSnapshot,
    remaining_pct: Option<f64>,
    /// The recorded window has reset; its old reading no longer describes capacity.
    reset_passed: bool,
    /// Display state derived in Rust; interfaces never recompute it.
    state: gnomcode_core::quota::QuotaState,
    /// Usage pace for exact or API readings, when it can be computed honestly.
    pace: Option<gnomcode_core::quota::QuotaPace>,
    /// The reading is older than the stale threshold and is shown as last seen.
    stale: bool,
    /// Display label: the window label, prefixed by the pool name (middle dot separator)
    /// when the provider has several pools.
    label: String,
    /// Pool display name; only set when the provider has more than one distinct pool.
    pool: Option<String>,
    /// Window label: "Session", "Weekly" or "Monthly".
    window_label: String,
    /// Why the opt-in live source is not refreshing this reading (e.g. expired Claude sign-in).
    #[serde(skip_serializing_if = "Option::is_none")]
    source_issue: Option<String>,
}

/// Quota views for the local API, annotated with why an opt-in live source has stopped updating.
fn quota_views_with_issues(snapshots: Vec<gnomcode_core::QuotaSnapshot>) -> Vec<QuotaPoolView> {
    let mut views = quota_views(snapshots);
    for view in &mut views {
        view.source_issue = crate::vendor_limits::issue(&view.snapshot.provider);
    }
    views
}

/// Display name for a pool id. Snake or kebab ids (`gemini_pro`) are title-cased
/// (`Gemini Pro`); ids that are already readable (`Claude and GPT models`) are kept verbatim.
fn pool_display_name(identifier: &str) -> String {
    let is_slug = !identifier.is_empty()
        && identifier
            .bytes()
            .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'_' || b == b'-');
    if !is_slug {
        return identifier.to_owned();
    }
    identifier
        .split(['_', '-'])
        .filter(|word| !word.is_empty())
        .map(|word| {
            let mut chars = word.chars();
            chars.next().map_or_else(String::new, |first| {
                first.to_uppercase().chain(chars).collect()
            })
        })
        .collect::<Vec<_>>()
        .join(" ")
}

pub(crate) fn quota_views(snapshots: Vec<gnomcode_core::QuotaSnapshot>) -> Vec<QuotaPoolView> {
    quota_views_at(snapshots, chrono::Utc::now())
}

pub(crate) fn quota_views_at(
    snapshots: Vec<gnomcode_core::QuotaSnapshot>,
    now: chrono::DateTime<chrono::Utc>,
) -> Vec<QuotaPoolView> {
    use gnomcode_core::quota;
    // Every source reports all of a provider's pools at once, so rows older than the provider's
    // latest snapshot belong to renamed or regrouped pools and are superseded.
    let mut latest = std::collections::HashMap::new();
    for snapshot in &snapshots {
        let seen = latest
            .entry(snapshot.provider.clone())
            .or_insert(snapshot.observed_at);
        *seen = (*seen).max(snapshot.observed_at);
    }
    let kept: Vec<_> = snapshots
        .into_iter()
        .filter(|snapshot| {
            latest
                .get(&snapshot.provider)
                .is_none_or(|at| *at - snapshot.observed_at <= chrono::Duration::minutes(10))
        })
        // A pool whose window reset over a week ago without a new reading is retired, not "awaiting".
        .filter(|snapshot| {
            snapshot
                .resets_at
                .is_none_or(|reset| now - reset < chrono::Duration::days(7))
        })
        .collect();
    let mut pools_by_provider: std::collections::HashMap<
        String,
        std::collections::HashSet<String>,
    > = std::collections::HashMap::new();
    for snapshot in &kept {
        pools_by_provider
            .entry(snapshot.provider.clone())
            .or_default()
            .insert(snapshot.limit_id.clone());
    }
    kept.into_iter()
        .map(|snapshot| {
            let window = match snapshot.window {
                gnomcode_core::QuotaWindow::FiveHour => "Session",
                gnomcode_core::QuotaWindow::Weekly => "Weekly",
                gnomcode_core::QuotaWindow::Monthly => "Monthly",
            };
            let pool = pools_by_provider
                .get(&snapshot.provider)
                .is_some_and(|pools| pools.len() > 1)
                .then(|| pool_display_name(&snapshot.limit_id));
            let label = pool.as_ref().map_or_else(
                || window.to_owned(),
                |name| format!("{name} \u{b7} {window}"),
            );
            QuotaPoolView {
                remaining_pct: quota::remaining_pct(&snapshot, now),
                reset_passed: snapshot.resets_at.is_some_and(|reset| reset <= now),
                state: quota::quota_state(&snapshot, now),
                pace: quota::quota_pace(&snapshot, now),
                stale: quota::is_stale(&snapshot, now),
                label,
                pool,
                window_label: window.to_owned(),
                snapshot,
                source_issue: None,
            }
        })
        .collect()
}

pub(crate) fn conversation_quota(
    snapshots: &[gnomcode_core::QuotaSnapshot],
    agent: &str,
    now: chrono::DateTime<chrono::Utc>,
) -> Vec<Value> {
    let provider = crate::agent_for_model("@default", Some(agent)).unwrap_or(agent);
    let pools: std::collections::HashSet<_> = snapshots
        .iter()
        .filter(|snapshot| snapshot.provider == provider)
        .map(|snapshot| snapshot.limit_id.as_str())
        .collect();
    quota_views_at(snapshots.iter().filter(|snapshot|snapshot.provider==provider).cloned().collect(), now).into_iter().map(|pool| {
        let window = match pool.snapshot.window {gnomcode_core::QuotaWindow::FiveHour=>"5h",gnomcode_core::QuotaWindow::Weekly=>"Weekly",gnomcode_core::QuotaWindow::Monthly=>"Monthly"};
        let label = if pools.len()>1 {format!("{} {window}",pool.snapshot.limit_id.replace(['-','_']," "))}else{window.to_owned()};
        let expired = pool.snapshot.resets_at.is_some_and(|reset|reset<=now);
        let stale = expired || now.signed_duration_since(pool.snapshot.observed_at)>chrono::Duration::minutes(2);
        json!({"label":label,"state":pool.state,"remaining_pct":if expired {None}else{pool.remaining_pct},"basis":pool.snapshot.basis,"observed_at":pool.snapshot.observed_at,"stale":stale,"window":pool.snapshot.window,"window_label":pool.window_label,"pool":pool.pool,"resets_at":pool.snapshot.resets_at,"reset_passed":pool.reset_passed,"pace":pool.pace})
    }).collect()
}

/// Recorded spend for one provider (SPEC 3.9); an estimate unless every turn was priced.
#[derive(Serialize)]
pub(crate) struct ProviderCost {
    today_usd: f64,
    last_30_days_usd: f64,
    basis: gnomcode_core::TrustLevel,
}

/// One provider card on the Limits view: windows, state and, when empty, how to turn them on.
#[derive(Serialize)]
pub(crate) struct ProviderOverview {
    /// Provider slug, e.g. `claude-code`.
    provider: String,
    display_name: String,
    /// First non-empty plan among the provider's windows.
    plan: Option<String>,
    /// Worst window by severity; unknown when there are no windows.
    state: gnomcode_core::quota::QuotaState,
    /// Sorted: session, weekly, monthly, then label.
    windows: Vec<QuotaPoolView>,
    /// Index into `windows` of the tightest window: highest severity, ties by lowest
    /// remaining percentage. `None` when there are no windows.
    headline_window: Option<usize>,
    updated_at: Option<chrono::DateTime<chrono::Utc>>,
    /// "Local logs", "Status line", "Provider API", "Language server" or "Off".
    source_label: String,
    /// Shown when `windows` is empty.
    enable_hint: Option<String>,
    enable_command: Option<String>,
    /// `None` when nothing was recorded in the last 30 days.
    cost: Option<ProviderCost>,
    /// Why the opt-in live source is not refreshing this provider's readings.
    #[serde(skip_serializing_if = "Option::is_none")]
    source_issue: Option<String>,
}

const CORE_PROVIDERS: [&str; 3] = ["claude-code", "codex", "antigravity"];

/// Sums recorded spend per agent slug. `ProviderReport.provider` is a display label
/// ("Claude Code", "OpenAI Codex"), so spend is keyed on `ModelReport.agent`, the same
/// slug quota snapshots use for `provider`.
fn provider_costs(
    today: &gnomcode_store::TimelineReport,
    last_30_days: &gnomcode_store::TimelineReport,
) -> std::collections::HashMap<String, ProviderCost> {
    use std::collections::HashMap;
    fn per_agent(report: &gnomcode_store::TimelineReport) -> HashMap<String, (f64, u64)> {
        let mut sums: HashMap<String, (f64, u64)> = HashMap::new();
        for model in report.providers.iter().flat_map(|p| &p.models) {
            let entry = sums.entry(model.agent.to_lowercase()).or_default();
            entry.0 += model.cost_usd;
            entry.1 += model.unpriced_turns;
        }
        sums
    }
    let today = per_agent(today);
    per_agent(last_30_days)
        .into_iter()
        .filter(|(_, (spend, _))| *spend > 0.0)
        .map(|(agent, (month_usd, unpriced))| {
            let today_usd = today.get(&agent).map_or(0.0, |(spend, _)| *spend);
            let basis = if unpriced > 0 {
                gnomcode_core::TrustLevel::Unknown
            } else {
                gnomcode_core::TrustLevel::Estimated
            };
            (
                agent,
                ProviderCost {
                    today_usd,
                    last_30_days_usd: month_usd,
                    basis,
                },
            )
        })
        .collect()
}

/// Display name, hint and enable command for a provider without readings.
fn provider_empty_state(
    slug: &str,
    claude_api: bool,
    antigravity_api: bool,
) -> (String, String, Option<String>) {
    let enable = |name: &str| Some(format!("gnomcode limits enable {name}"));
    match slug {
        "claude-code" if claude_api => (
            "Claude Code".into(),
            "Waiting for the first Claude reading.".into(),
            None,
        ),
        "claude-code" => (
            "Claude Code".into(),
            "Limits are off for Claude Code.".into(),
            enable("claude"),
        ),
        "codex" => (
            "Codex".into(),
            "Appears after your next Codex request.".into(),
            None,
        ),
        "antigravity" if antigravity_api => (
            "Antigravity".into(),
            "Start an Antigravity agent to read limits.".into(),
            None,
        ),
        "antigravity" => (
            "Antigravity".into(),
            "Limits are off for Antigravity.".into(),
            enable("antigravity"),
        ),
        other => (pool_display_name(other), "No reading yet.".into(), None),
    }
}

fn provider_display_name(slug: &str) -> String {
    match slug {
        "claude-code" => "Claude Code".into(),
        "codex" => "Codex".into(),
        "antigravity" => "Antigravity".into(),
        other => pool_display_name(other),
    }
}

/// Builds one overview per provider from already-derived quota views.
fn provider_overviews(
    views: Vec<QuotaPoolView>,
    mut costs: std::collections::HashMap<String, ProviderCost>,
    claude_api: bool,
    antigravity_api: bool,
) -> Vec<ProviderOverview> {
    use gnomcode_core::TrustLevel;
    let mut by_provider: std::collections::BTreeMap<String, Vec<QuotaPoolView>> =
        std::collections::BTreeMap::new();
    for provider in CORE_PROVIDERS {
        by_provider.entry(provider.to_owned()).or_default();
    }
    for view in views {
        by_provider
            .entry(view.snapshot.provider.clone())
            .or_default()
            .push(view);
    }
    let mut order: Vec<String> = CORE_PROVIDERS.iter().map(|p| (*p).to_owned()).collect();
    order.extend(
        by_provider
            .keys()
            .filter(|slug| !CORE_PROVIDERS.contains(&slug.as_str()))
            .cloned(),
    );
    order
        .into_iter()
        .filter_map(|slug| {
            let mut windows = by_provider.remove(&slug)?;
            windows.sort_by(|a, b| {
                (window_rank(a.snapshot.window), &a.label)
                    .cmp(&(window_rank(b.snapshot.window), &b.label))
            });
            let has_exact = windows
                .iter()
                .any(|w| w.snapshot.basis == TrustLevel::Exact);
            let source_label = match slug.as_str() {
                "claude-code" if claude_api => "Provider API",
                "claude-code" if has_exact => "Status line",
                "claude-code" => "Off",
                "antigravity" if antigravity_api => "Language server",
                "antigravity" => "Off",
                _ => "Local logs",
            };
            let (display_name, enable_hint, enable_command) = if windows.is_empty() {
                let (name, hint, command) =
                    provider_empty_state(&slug, claude_api, antigravity_api);
                (name, Some(hint), command)
            } else {
                (provider_display_name(&slug), None, None)
            };
            Some(ProviderOverview {
                headline_window: headline_window(&windows),
                plan: windows.iter().find_map(|w| w.snapshot.plan.clone()),
                state: windows
                    .iter()
                    .map(|w| w.state)
                    .max_by_key(|state| state.severity())
                    .unwrap_or(gnomcode_core::quota::QuotaState::Unknown),
                updated_at: windows.iter().map(|w| w.snapshot.observed_at).max(),
                cost: costs.remove(&slug),
                source_issue: crate::vendor_limits::issue(&slug),
                provider: slug,
                display_name,
                windows,
                source_label: source_label.to_owned(),
                enable_hint,
                enable_command,
            })
        })
        .collect()
}

/// Index of the window with the highest severity, ties broken by the lowest remaining
/// percentage (windows without a remaining value rank last); the earliest window wins a full tie.
fn headline_window(windows: &[QuotaPoolView]) -> Option<usize> {
    windows
        .iter()
        .enumerate()
        .min_by(|(_, a), (_, b)| {
            b.state.severity().cmp(&a.state.severity()).then_with(|| {
                let left = |w: &QuotaPoolView| w.remaining_pct.unwrap_or(f64::INFINITY);
                left(a).total_cmp(&left(b))
            })
        })
        .map(|(index, _)| index)
}

fn window_rank(window: gnomcode_core::QuotaWindow) -> u8 {
    match window {
        gnomcode_core::QuotaWindow::FiveHour => 0,
        gnomcode_core::QuotaWindow::Weekly => 1,
        gnomcode_core::QuotaWindow::Monthly => 2,
    }
}


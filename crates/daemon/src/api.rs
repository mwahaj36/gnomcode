async fn export_handler(
    headers: HeaderMap,
    State(state): State<AppState>,
    Query(params): Query<ReportQueryParams>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    let range = params.range.as_deref().unwrap_or("30d");
    if !matches!(range, "today" | "7d" | "30d" | "all") {
        return Err(StatusCode::BAD_REQUEST);
    }
    let db = state.db.lock().await;
    let report = db
        .generate_usage_report_timeline(range, params.from.as_deref(), params.to.as_deref())
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    if params.format.as_deref() == Some("csv") {
        let mut csv = String::from(
            "agent,model,turns,input_tokens,output_tokens,cache_read_tokens,cost_usd,cache_savings_usd\n",
        );
        for prov in &report.providers {
            for m in &prov.models {
                use std::fmt::Write as _;
                let _ = writeln!(
                    csv,
                    "{},{},{},{},{},{},{:.4},{:.4}",
                    prov.provider,
                    m.model,
                    m.turn_count,
                    m.input_tokens,
                    m.output_tokens,
                    m.cache_read_tokens,
                    m.cost_usd,
                    m.cache_savings_usd
                );
            }
        }
        Ok((
            [
                (header::CONTENT_TYPE, "text/csv; charset=utf-8"),
                (
                    header::CONTENT_DISPOSITION,
                    "attachment; filename=spawnt-report.csv",
                ),
            ],
            csv,
        )
            .into_response())
    } else {
        Ok((
            [
                (header::CONTENT_TYPE, "application/json"),
                (
                    header::CONTENT_DISPOSITION,
                    "attachment; filename=spawnt-report.json",
                ),
            ],
            Json(report),
        )
            .into_response())
    }
}


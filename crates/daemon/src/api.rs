/// Query parameters for reading a repository file.
#[derive(Debug, Deserialize)]
pub struct RepoFileQuery {
    /// Absolute or relative path to the repo root.
    pub repo: String,
    /// Relative path to the file inside the repo.
    pub path: String,
}

async fn repo_file_get_handler(
    headers: HeaderMap,
    Query(query): Query<RepoFileQuery>,
    State(state): State<AppState>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    if query.repo.trim().is_empty() || query.path.trim().is_empty() {
        return Err(StatusCode::BAD_REQUEST);
    }

    let relative = std::path::Path::new(&query.path);
    if relative.components().any(|c| {
        matches!(
            c,
            std::path::Component::ParentDir
                | std::path::Component::RootDir
                | std::path::Component::Prefix(_)
        )
    }) {
        return Err(StatusCode::BAD_REQUEST);
    }

    let repo_path = std::path::Path::new(&query.repo);
    let Ok(canonical_repo) = repo_path.canonicalize() else {
        return Err(StatusCode::BAD_REQUEST);
    };

    if !canonical_repo.is_dir() {
        return Err(StatusCode::BAD_REQUEST);
    }

    let target_path = canonical_repo.join(&query.path);
    let Ok(canonical_target) = target_path.canonicalize() else {
        return Err(StatusCode::NOT_FOUND);
    };

    // Strict containment inside repo root (path-traversal and symlink escape defense)
    if !canonical_target.starts_with(&canonical_repo) {
        return Err(StatusCode::BAD_REQUEST);
    }

    if !canonical_target.is_file() {
        return Err(StatusCode::BAD_REQUEST);
    }

    let metadata =
        std::fs::metadata(&canonical_target).map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;
    if metadata.len() > 512 * 1024 {
        return Err(StatusCode::PAYLOAD_TOO_LARGE);
    }

    let content = std::fs::read_to_string(&canonical_target)
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;
    Ok(Json(json!({
        "path": query.path,
        "content": content
    })))
}

/// Query parameters for inspecting git workspace diffs.
#[derive(Debug, Deserialize)]
pub struct RepoDiffQuery {
    /// Path to the repository root.
    pub repo: String,
}

async fn repo_diff_get_handler(
    headers: HeaderMap,
    Query(query): Query<RepoDiffQuery>,
    State(state): State<AppState>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    let repo_path = std::path::Path::new(&query.repo);
    let Ok(canonical_repo) = repo_path.canonicalize() else {
        return Err(StatusCode::BAD_REQUEST);
    };

    if !canonical_repo.is_dir() {
        return Err(StatusCode::BAD_REQUEST);
    }

    #[cfg(windows)]
    use std::os::windows::process::CommandExt as _;

    let mut diff_cmd = std::process::Command::new("git");
    diff_cmd.args(["diff", "HEAD"]).current_dir(&canonical_repo);
    #[cfg(windows)]
    diff_cmd.creation_flags(0x0800_0000);
    let diff_output = diff_cmd.output();

    let mut status_cmd = std::process::Command::new("git");
    status_cmd
        .args(["status", "--porcelain"])
        .current_dir(&canonical_repo);
    #[cfg(windows)]
    status_cmd.creation_flags(0x0800_0000);
    let status_output = status_cmd.output();

    let diff_str = diff_output
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .unwrap_or_default();

    let status_str = status_output
        .ok()
        .and_then(|o| String::from_utf8(o.stdout).ok())
        .unwrap_or_default();

    Ok(Json(json!({
        "repo": query.repo,
        "diff": diff_str,
        "status": status_str
    })))
}

/// Request payload to switch a session to a target model with zero-token handoff.
#[derive(Debug, Deserialize)]
pub struct SwitchSessionRequest {
    /// Target model to switch to.
    pub target_model: String,
    /// Optional agent surface identifier.
    pub agent: Option<String>,
}

async fn switch_session_handler(
    headers: HeaderMap,
    Path(id): Path<String>,
    State(state): State<AppState>,
    Json(payload): Json<SwitchSessionRequest>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    let db = state.db.lock().await;

    let history = db.get_session_chat(&id, Some(50)).unwrap_or_default();
    let turn_count = history.len() as u32;

    let mut user_prompts = Vec::new();
    for evt in &history {
        if evt.role == spawnt_core::ChatRole::User {
            user_prompts.push(evt.content.clone());
        }
    }
    let summary = if user_prompts.is_empty() {
        format!("Continuation of session {id}")
    } else {
        user_prompts.join("; ")
    };
    let redacted_summary = spawnt_core::redact::redact_chat_content(&summary);

    // Compile zero-token handoff packet
    let packet = spawnt_core::HandoffPacket {
        session_id: id.clone(),
        source_model: "previous".to_owned(),
        target_model: payload.target_model.clone(),
        prompt_summary: redacted_summary,
        touched_files: Vec::new(),
        turn_count,
        created_at: chrono::Utc::now(),
    };

    // Record system chat event documenting switch
    let handoff_evt = spawnt_core::ChatEvent {
        event_id: format!(
            "switch-{}-{}",
            id,
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .map(|d| d.as_nanos())
                .unwrap_or(0)
        ),
        session_id: id.clone(),
        turn_index: (turn_count + 1) as i64,
        role: spawnt_core::ChatRole::System,
        content: format!("Model switched to {}", payload.target_model),
        tool_name: None,
        status: Some("switched".to_owned()),
        created_at: chrono::Utc::now(),
    };
    let _ = db.insert_chat_event(&handoff_evt);

    Ok(Json(packet))
}


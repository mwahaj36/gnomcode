//! Local loopback axum HTTP & WebSocket API (`SPEC §3.1`, `§4.4`).
//!
//! Enforces:
//! 1. Strict loopback binding (`127.0.0.1`).
//! 2. `Host` and `Origin` header validation against `127.0.0.1` and `localhost` (DNS rebinding defense).
//! 3. Bearer token authorization on all endpoints.

use axum::{
    Router,
    extract::{Query, State},
    http::{HeaderMap, StatusCode},
    response::{IntoResponse, Json},
    routing::get,
};
use fleethud_store::{Database, UserProfile};
use serde::{Deserialize, Serialize};
use serde_json::json;
use std::sync::Arc;
use tokio::sync::Mutex;

/// Server application state shared across HTTP handlers.
#[derive(Clone)]
pub struct AppState {
    /// Database handle wrapped with tokio Mutex.
    pub db: Arc<Mutex<Database>>,
    /// Expected bearer token generated by `DaemonLock`.
    pub bearer_token: String,
}

/// Query parameters for listing sessions with pagination & filters.
#[derive(Debug, Deserialize, Default)]
pub struct SessionQueryParams {
    /// 1-indexed page number.
    pub page: Option<usize>,
    /// Limit per page (default 10).
    pub limit: Option<usize>,
    /// Agent slug filter (e.g. `antigravity`, `codex`, `claude-code`, or `all`).
    pub agent: Option<String>,
    /// Status filter (`active`, `idle`, or `all`).
    pub status: Option<String>,
}

/// Query parameters for reports.
#[derive(Debug, Deserialize, Default)]
pub struct ReportQueryParams {
    /// Range filter (`today`, `7d`, `30d`, `all`, `custom`).
    pub range: Option<String>,
    /// Custom ISO start timestamp.
    pub from: Option<String>,
    /// Custom ISO end timestamp.
    pub to: Option<String>,
}

/// Daemon health endpoint response.
#[derive(Debug, Serialize)]
pub struct HealthResponse {
    /// Server health status.
    pub status: &'static str,
    /// Current UTC timestamp.
    pub timestamp: String,
}

const CONSOLE_HTML: &str = include_str!("console.html");

/// Builds the axum router for FleetHUD local API and embedded console.
pub fn build_router(state: AppState) -> Router {
    Router::new()
        .route("/", get(console_handler))
        .route("/console", get(console_handler))
        .route("/health", get(health_handler))
        .route("/api/v1/sessions", get(list_sessions_handler))
        .route("/api/v1/report", get(report_handler))
        .route("/api/v1/quota", get(quota_handler))
        .route(
            "/api/v1/user",
            get(user_get_handler).post(user_post_handler),
        )
        .route(
            "/api/v1/pricing/custom",
            get(custom_pricing_get_handler)
                .post(custom_pricing_post_handler)
                .delete(custom_pricing_delete_handler),
        )
        .route(
            "/api/v1/auth/session",
            get(auth_session_get_handler)
                .post(auth_session_post_handler)
                .delete(auth_session_delete_handler),
        )
        .route("/api/v1/stats", get(stats_handler))
        .route("/api/v1/supabase-config", get(supabase_config_handler))
        .route("/api/v1/live", get(live_snapshot_handler))
        .with_state(state)
}

async fn console_handler() -> impl IntoResponse {
    axum::response::Html(CONSOLE_HTML)
}

fn validate_auth(headers: &HeaderMap, expected_token: &str) -> Result<(), StatusCode> {
    // 1. Host header validation
    if let Some(host) = headers.get("host").and_then(|h| h.to_str().ok()) {
        let clean = host.split(':').next().unwrap_or(host);
        if clean != "127.0.0.1" && clean != "localhost" {
            return Err(StatusCode::FORBIDDEN);
        }
    }

    // 2. Origin header validation (if present)
    if let Some(origin) = headers.get("origin").and_then(|o| o.to_str().ok()) {
        let clean = origin
            .trim_start_matches("http://")
            .trim_start_matches("https://");
        let host_only = clean.split(':').next().unwrap_or(clean);
        if host_only != "127.0.0.1" && host_only != "localhost" {
            return Err(StatusCode::FORBIDDEN);
        }
    }

    // 3. Bearer authorization header validation
    let Some(auth) = headers.get("authorization").and_then(|a| a.to_str().ok()) else {
        return Err(StatusCode::UNAUTHORIZED);
    };

    let Some(token) = auth.strip_prefix("Bearer ") else {
        return Err(StatusCode::UNAUTHORIZED);
    };

    if token.trim() == expected_token {
        Ok(())
    } else {
        Err(StatusCode::UNAUTHORIZED)
    }
}

async fn health_handler(
    headers: HeaderMap,
    State(state): State<AppState>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    Ok(Json(HealthResponse {
        status: "ok",
        timestamp: chrono::Utc::now().to_rfc3339(),
    }))
}

async fn list_sessions_handler(
    headers: HeaderMap,
    State(state): State<AppState>,
    Query(params): Query<SessionQueryParams>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    let page = params.page.unwrap_or(1).max(1);
    let limit = params.limit.unwrap_or(10).clamp(1, 100);
    let offset = (page - 1) * limit;

    let db = state.db.lock().await;
    let (sessions, total_count) = db
        .list_sessions_paginated(
            params.agent.as_deref(),
            params.status.as_deref(),
            offset,
            limit,
        )
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    let (_, active_count) = db
        .list_sessions_paginated(None, Some("active"), 0, 1)
        .unwrap_or_default();

    #[derive(Serialize)]
    struct PaginatedResponse {
        sessions: Vec<fleethud_store::SessionListItem>,
        total_count: usize,
        page: usize,
        limit: usize,
        total_pages: usize,
        active_count: usize,
    }

    let total_pages = total_count.div_ceil(limit);

    Ok(Json(PaginatedResponse {
        sessions,
        total_count,
        page,
        limit,
        total_pages: total_pages.max(1),
        active_count,
    }))
}

async fn report_handler(
    headers: HeaderMap,
    State(state): State<AppState>,
    Query(params): Query<ReportQueryParams>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    let range = params.range.as_deref().unwrap_or("all");
    let db = state.db.lock().await;

    let report = db
        .generate_usage_report_timeline(range, params.from.as_deref(), params.to.as_deref())
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    let user_profile = db
        .get_user_profile()
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;

    #[derive(Serialize)]
    struct PlanRoiInfo {
        provider: String,
        plan_usd: f64,
        monthly_plan_usd: f64,
        spend_usd: f64,
        multiplier: f64,
        net_savings_usd: f64,
        period_label: String,
    }

    #[derive(Serialize)]
    struct EnhancedReport {
        timeline: fleethud_store::TimelineReport,
        user_profile: UserProfile,
        roi_by_provider: Vec<PlanRoiInfo>,
        combined_roi: PlanRoiInfo,
    }

    let (time_factor, period_label): (f64, &str) = match range {
        "today" | "24h" => (1.0 / 30.0, "day"),
        "7d" => (7.0 / 30.0, "7d"),
        "30d" => (1.0, "mo"),
        _ => {
            if let (Some(early_s), Some(late_s)) = (&report.earliest_at, &report.latest_at) {
                if let (Ok(e_dt), Ok(l_dt)) = (
                    chrono::DateTime::parse_from_rfc3339(early_s),
                    chrono::DateTime::parse_from_rfc3339(late_s),
                ) {
                    let days = (l_dt - e_dt).num_days().max(1) as f64;
                    (days / 30.0, "period")
                } else {
                    (1.0, "period")
                }
            } else {
                (1.0, "period")
            }
        }
    };

    let mut roi_by_provider = Vec::new();
    let mut combined_plan = 0.0;

    let get_spend = |prov_names: &[&str]| -> f64 {
        report
            .providers
            .iter()
            .find(|p| {
                prov_names
                    .iter()
                    .any(|name| p.provider.eq_ignore_ascii_case(name))
            })
            .map_or(0.0, |p| p.total_cost_usd)
    };

    let claude_spend = get_spend(&["Claude Code", "Anthropic", "Anthropic (Claude)"]);
    let openai_spend = get_spend(&["OpenAI Codex", "OpenAI", "OpenAI (Codex)"]);
    let google_spend = get_spend(&["Google Antigravity", "Google", "Google (Antigravity)"]);

    if user_profile.claude_plan_usd > 0.0 && claude_spend > 0.0 {
        let eff_plan = user_profile.claude_plan_usd * time_factor;
        combined_plan += eff_plan;
        let roi = fleethud_core::pricing::calculate_plan_roi(claude_spend, eff_plan);
        roi_by_provider.push(PlanRoiInfo {
            provider: "Claude Code".to_owned(),
            plan_usd: eff_plan,
            monthly_plan_usd: user_profile.claude_plan_usd,
            spend_usd: claude_spend,
            multiplier: roi.multiplier,
            net_savings_usd: roi.net_savings_usd,
            period_label: period_label.to_owned(),
        });
    }

    if user_profile.openai_plan_usd > 0.0 && openai_spend > 0.0 {
        let eff_plan = user_profile.openai_plan_usd * time_factor;
        combined_plan += eff_plan;
        let roi = fleethud_core::pricing::calculate_plan_roi(openai_spend, eff_plan);
        roi_by_provider.push(PlanRoiInfo {
            provider: "OpenAI Codex".to_owned(),
            plan_usd: eff_plan,
            monthly_plan_usd: user_profile.openai_plan_usd,
            spend_usd: openai_spend,
            multiplier: roi.multiplier,
            net_savings_usd: roi.net_savings_usd,
            period_label: period_label.to_owned(),
        });
    }

    if user_profile.google_plan_usd > 0.0 && google_spend > 0.0 {
        let eff_plan = user_profile.google_plan_usd * time_factor;
        combined_plan += eff_plan;
        let roi = fleethud_core::pricing::calculate_plan_roi(google_spend, eff_plan);
        roi_by_provider.push(PlanRoiInfo {
            provider: "Google Antigravity".to_owned(),
            plan_usd: eff_plan,
            monthly_plan_usd: user_profile.google_plan_usd,
            spend_usd: google_spend,
            multiplier: roi.multiplier,
            net_savings_usd: roi.net_savings_usd,
            period_label: period_label.to_owned(),
        });
    }

    let combined_roi_calc =
        fleethud_core::pricing::calculate_plan_roi(report.total_cost_usd, combined_plan);
    let combined_roi = PlanRoiInfo {
        provider: "All Plans (Combined)".to_owned(),
        plan_usd: combined_plan,
        monthly_plan_usd: user_profile.claude_plan_usd
            + user_profile.openai_plan_usd
            + user_profile.google_plan_usd,
        spend_usd: report.total_cost_usd,
        multiplier: combined_roi_calc.multiplier,
        net_savings_usd: combined_roi_calc.net_savings_usd,
        period_label: period_label.to_owned(),
    };

    Ok(Json(EnhancedReport {
        timeline: report,
        user_profile,
        roi_by_provider,
        combined_roi,
    }))
}


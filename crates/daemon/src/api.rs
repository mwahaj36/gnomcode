//! Local loopback axum HTTP & WebSocket API (`SPEC §3.1`, `§4.4`).
//!
//! Enforces:
//! 1. Strict loopback binding (`127.0.0.1`).
//! 2. `Host` and `Origin` header validation against `127.0.0.1` and `localhost` (DNS rebinding defense).
//! 3. Bearer token authorization on all endpoints.

use axum::{
    Router,
    extract::{Query, State},
    http::{HeaderMap, StatusCode},
    response::{IntoResponse, Json},
    routing::get,
};
use fleethud_store::Database;
use serde::{Deserialize, Serialize};
use std::sync::Arc;
use tokio::sync::Mutex;

/// Server application state shared across HTTP handlers.
#[derive(Clone)]
pub struct AppState {
    /// Database handle wrapped with tokio Mutex.
    pub db: Arc<Mutex<Database>>,
    /// Expected bearer token generated by `DaemonLock`.
    pub bearer_token: String,
}

/// Query parameters for listing sessions.
#[derive(Debug, Deserialize)]
pub struct ListParams {
    /// Maximum count of sessions to return.
    pub limit: Option<usize>,
}

/// Daemon health endpoint response.
#[derive(Debug, Serialize)]
pub struct HealthResponse {
    /// Server health status.
    pub status: &'static str,
    /// Current UTC timestamp.
    pub timestamp: String,
}

const DASHBOARD_HTML: &str = include_str!("dashboard.html");

/// Builds the axum router for FleetHUD local API and embedded dashboard.
pub fn build_router(state: AppState) -> Router {
    Router::new()
        .route("/", get(dashboard_handler))
        .route("/health", get(health_handler))
        .route("/api/v1/sessions", get(list_sessions_handler))
        .route("/api/v1/report", get(report_handler))
        .route("/api/v1/quota", get(quota_handler))
        .with_state(state)
}

async fn dashboard_handler() -> impl IntoResponse {
    axum::response::Html(DASHBOARD_HTML)
}

fn validate_auth(headers: &HeaderMap, expected_token: &str) -> Result<(), StatusCode> {
    // 1. Host header validation
    if let Some(host) = headers.get("host").and_then(|h| h.to_str().ok()) {
        let clean = host.split(':').next().unwrap_or(host);
        if clean != "127.0.0.1" && clean != "localhost" {
            return Err(StatusCode::FORBIDDEN);
        }
    }

    // 2. Origin header validation (if present)
    if let Some(origin) = headers.get("origin").and_then(|o| o.to_str().ok()) {
        let clean = origin
            .trim_start_matches("http://")
            .trim_start_matches("https://");
        let host_only = clean.split(':').next().unwrap_or(clean);
        if host_only != "127.0.0.1" && host_only != "localhost" {
            return Err(StatusCode::FORBIDDEN);
        }
    }

    // 3. Bearer authorization header validation
    let Some(auth) = headers.get("authorization").and_then(|a| a.to_str().ok()) else {
        return Err(StatusCode::UNAUTHORIZED);
    };

    let Some(token) = auth.strip_prefix("Bearer ") else {
        return Err(StatusCode::UNAUTHORIZED);
    };

    if token.trim() == expected_token {
        Ok(())
    } else {
        Err(StatusCode::UNAUTHORIZED)
    }
}

async fn health_handler(
    headers: HeaderMap,
    State(state): State<AppState>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    Ok(Json(HealthResponse {
        status: "ok",
        timestamp: chrono::Utc::now().to_rfc3339(),
    }))
}

async fn list_sessions_handler(
    headers: HeaderMap,
    State(state): State<AppState>,
    Query(params): Query<ListParams>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    let limit = params.limit.unwrap_or(20);
    let db = state.db.lock().await;
    let sessions = db
        .list_active_sessions(limit)
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;
    Ok(Json(sessions))
}

async fn report_handler(
    headers: HeaderMap,
    State(state): State<AppState>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    let db = state.db.lock().await;
    let rows = db
        .generate_usage_report()
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;
    let mut total_cost = 0.0;
    let mut total_savings = 0.0;
    for r in &rows {
        total_cost += r.total_cost_usd;
        total_savings += r.total_cache_savings_usd;
    }

    #[derive(Serialize)]
    struct FullReport {
        total_cost_usd: f64,
        total_cache_savings_usd: f64,
        items_count: usize,
    }

    Ok(Json(FullReport {
        total_cost_usd: total_cost,
        total_cache_savings_usd: total_savings,
        items_count: rows.len(),
    }))
}

async fn quota_handler(
    headers: HeaderMap,
    State(state): State<AppState>,
) -> Result<impl IntoResponse, StatusCode> {
    validate_auth(&headers, &state.bearer_token)?;
    let db = state.db.lock().await;
    let quota = db
        .get_latest_quota_snapshots()
        .map_err(|_| StatusCode::INTERNAL_SERVER_ERROR)?;
    Ok(Json(quota))
}

#[cfg(test)]
mod tests {
    use super::{AppState, build_router};
    use axum::body::Body;
    use axum::http::{Request, StatusCode};
    use fleethud_store::Database;
    use std::sync::Arc;
    use tokio::sync::Mutex;
    use tower::ServiceExt as _;

    #[tokio::test]
    async fn rejects_missing_bearer_token() {
        let db = Database::open_in_memory().expect("in-memory db");
        let state = AppState {
            db: Arc::new(Mutex::new(db)),
            bearer_token: "secret-test-token".to_owned(),
        };
        let app = build_router(state);

        let req = Request::builder()
            .uri("/health")
            .header("Host", "127.0.0.1:41738")
            .body(Body::empty())
            .expect("request");

        let res = app.oneshot(req).await.expect("response");
        assert_eq!(res.status(), StatusCode::UNAUTHORIZED);
    }

    #[tokio::test]
    async fn rejects_invalid_host_header_dns_rebinding() {
        let db = Database::open_in_memory().expect("in-memory db");
        let state = AppState {
            db: Arc::new(Mutex::new(db)),
            bearer_token: "secret-test-token".to_owned(),
        };
        let app = build_router(state);

        let req = Request::builder()
            .uri("/health")
            .header("Host", "evil-website.com")
            .header("Authorization", "Bearer secret-test-token")
            .body(Body::empty())
            .expect("request");

        let res = app.oneshot(req).await.expect("response");
        assert_eq!(res.status(), StatusCode::FORBIDDEN);
    }

    #[tokio::test]
    async fn accepts_valid_loopback_and_token() {
        let db = Database::open_in_memory().expect("in-memory db");
        let state = AppState {
            db: Arc::new(Mutex::new(db)),
            bearer_token: "secret-test-token".to_owned(),
        };
        let app = build_router(state);

        let req = Request::builder()
            .uri("/health")
            .header("Host", "127.0.0.1:41738")
            .header("Authorization", "Bearer secret-test-token")
            .body(Body::empty())
            .expect("request");

        let res = app.oneshot(req).await.expect("response");
        assert_eq!(res.status(), StatusCode::OK);
    }
}

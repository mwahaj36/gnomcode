import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const branding = JSON.parse(fs.readFileSync(path.join(root, 'web/branding.json'), 'utf8'));
const url = new URL(branding.baseUrl);
if (url.protocol !== 'https:' || url.username || url.password || url.search || url.hash || url.pathname !== '/') throw new Error('Branding requires an HTTPS origin.');
const check = process.argv.includes('--check');
let stale = false;
function output(relative, text) {
  const file = path.join(root, relative);
  if (fs.existsSync(file) && fs.readFileSync(file, 'utf8').replaceAll('\r\n', '\n') === text) return;
  if (check) { console.error(`Stale branding: ${relative}`); stale = true; }
  else fs.writeFileSync(file, text);
}
output('apps/desktop/src/branding.ts', `// Generated by scripts/sync-branding.mjs.\nexport const branding = ${JSON.stringify(branding, null, 2)} as const;\n`);
output('npm/gnomcode/bin/branding.json', JSON.stringify(branding, null, 2) + '\n');
for (const extension of ['sh', 'ps1']) {
  const relative = `scripts/install.${extension}`;
  let text = fs.readFileSync(path.join(root, relative), 'utf8').replaceAll('\r\n', '\n');
  text = text.replace(/(BASE_URL|\$BaseUrl)="[^"]+"/g, `$1="${branding.baseUrl}/downloads"`)
    .replace(/(\$BaseUrl) = "[^"]+"/g, `$1 = "${branding.baseUrl}/downloads"`);
  output(relative, text);
  output(`web/public/downloads/install.${extension}`, text);
}
if (stale) process.exitCode = 1;
